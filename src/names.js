/** The name of a feature, `{n}` replaced by its number. */
export function featureName(name, lang, n) {
  const text = (NAMES[lang] ?? NAMES[DEFAULT_LANGUAGE])[name] ?? NAMES.en[name] ?? name;
  return n === undefined ? text : text.replace('{n}', String(n));
}

